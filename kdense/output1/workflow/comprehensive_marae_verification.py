def verify_csv_file(filepath, required_columns, file_description):
    """Verify CSV file exists and contains required MA-RAE columns."""
    print(f"\n{'='*80}")
    print(f"VERIFYING: {file_description}")
    print(f"File: {filepath}")
    print(f"{'='*80}")

    if not filepath.exists():
        print(f"❌ FAIL: File does not exist")
        return False, None

    print(f"✓ File exists")

    # Read CSV
    df = pd.read_csv(filepath)
    print(f"✓ File is readable")
    print(f"✓ Shape: {df.shape[0]} rows × {df.shape[1]} columns")
    print(f"✓ Columns: {list(df.columns)}")

    # Check for required columns
    missing_cols = [col for col in required_columns if col not in df.columns]
    if missing_cols:
        print(f"❌ FAIL: Missing required columns: {missing_cols}")
        return False, None

    print(f"✓ All required MA-RAE columns present: {required_columns}")

    # Check for NaN/Inf in MA-RAE columns
    for col in required_columns:
        if col in df.columns:
            nan_count = df[col].isna().sum()
            inf_count = np.isinf(df[col]).sum()
            print(f"✓ Column '{col}': {nan_count} NaN, {inf_count} Inf values")

            if nan_count > 0 or inf_count > 0:
                print(f"⚠️  WARNING: Found NaN or Inf values in {col}")

    # Display MA-RAE statistics
    print(f"\nMA-RAE Statistics:")
    for col in required_columns:
        if col in df.columns:
            values = df[col].dropna()
            if len(values) > 0:
                print(f"  {col}:")
                print(f"    Min: {values.min():.4f}")
                print(f"    Max: {values.max():.4f}")
                print(f"    Mean: {values.mean():.4f}")
                print(f"    Median: {values.median():.4f}")

    print(f"\n✅ PASS: {file_description} verification complete")
    return True, df

def verify_text_report(filepath, search_terms, file_description):
    """Verify text report contains MA-RAE information."""
    print(f"\n{'='*80}")
    print(f"VERIFYING: {file_description}")
    print(f"File: {filepath}")
    print(f"{'='*80}")

    if not filepath.exists():
        print(f"❌ FAIL: File does not exist")
        return False

    print(f"✓ File exists")

    # Read file
    with open(filepath, 'r') as f:
        content = f.read()

    print(f"✓ File is readable")
    print(f"✓ File size: {len(content)} characters")

    # Search for MA-RAE terms
    found_terms = []
    missing_terms = []

    for term in search_terms:
        if term.lower() in content.lower():
            found_terms.append(term)
            # Count occurrences
            count = content.lower().count(term.lower())
            print(f"✓ Found '{term}' ({count} occurrences)")
        else:
            missing_terms.append(term)
            print(f"❌ Missing '{term}'")

    if missing_terms:
        print(f"\n⚠️  WARNING: Some MA-RAE terms not found: {missing_terms}")
        return False

    print(f"\n✅ PASS: {file_description} verification complete")
    return True

